function normalizeArabic(text) {
    const easternDigits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
    let res = text || '';
    for (let i = 0; i < 10; i++) {
        res = res.split(easternDigits[i]).join(i.toString());
    }
    return res
        .replace(/[أإآ]/g, 'ا')
        .replace(/ة/g, 'ه')
        .replace(/ى/g, 'ي')
        .replace(/[ًٌٍَُِّْ]/g, '')
        .trim()
        .toLowerCase();
}

