async function startBot() {
    const { state, saveCreds } = await useMultiFileAuthState('auth_info');
    const { version } = await fetchLatestBaileysVersion();

const sock = makeWASocket({
    auth: state,
    logger: pino({ level: 'silent' }),
    browser: ["Ubuntu", "Chrome", "20.0.04"]
});
    sock.ev.on('creds.update', saveCreds);

    sock.ev.on('connection.update', (update) => {
        const { connection, lastDisconnect, qr } = update;

        if (qr) {
            console.log('\n📱 امسح رمز QR التالي من تطبيق الواتساب (الإعدادات -> الأجهزة المرتبطة -> ربط جهاز):');
            qrcode.generate(qr, { small: true });
        }

        if (connection === 'close') {
            const statusCode = lastDisconnect?.error?.output?.statusCode;
            const shouldReconnect = statusCode !== DisconnectReason.loggedOut;
            console.log('⚠️ انقطع الاتصال، إعادة المحاولة:', shouldReconnect);
            if (shouldReconnect) {
                setTimeout(startBot, 3000);
            } else {
                console.log('❌ تم تسجيل الخروج من الواتساب. احذف مجلد auth_info وأعد تشغيل السيرفر لمسح QR جديد.');
            }
        } else if (connection === 'open') {
            console.log('✅ تم تشغيل بوت مستشفى الأنهار التخصصي بنجاح وهو يعمل الآن 24/7!');
        }
    });

    sock.ev.on('messages.upsert', async ({ messages, type }) => {
        if (type !== 'notify') return;

        const msg = messages[0];
        if (!msg.message || msg.key.fromMe) return;

        const sender = msg.key.remoteJid;
        // تجاهل الحالات والمجموعات والقنوات
        if (!sender || sender === 'status@broadcast' || sender.endsWith('@g.us') || sender.endsWith('@newsletter')) return;

        const messageContent = msg.message?.ephemeralMessage?.message || msg.message;
        const rawText =
            messageContent?.conversation ||
            messageContent?.extendedTextMessage?.text ||
            '';

        if (!rawText.trim()) return;

        const patientPhone = (msg.key.remoteJidAlt || sender).split('@')[0];

        try {
            await processBotReply(sock, sender, rawText.trim(), msg.pushName, patientPhone);
        } catch (err) {
            console.error('خطأ أثناء معالجة الرسالة:', err);
        }
    });
}

// منع توقف البوت عند أي خطأ شبكي مفاجئ
process.on('uncaughtException', (err) => console.error('Uncaught Exception:', err));
process.on('unhandledRejection', (err) => console.error('Unhandled Rejection:', err));

startBot();